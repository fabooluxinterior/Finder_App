/// One illustrated person on a pastel card (welcome art, empty states). Used
/// where a real photo would be wrong: no real person is depicted.
class IllustratedPerson extends StatelessWidget {
  const IllustratedPerson({super.key, required this.index});
  final int index;

  @override
  Widget build(BuildContext context) {
    final (a, b, _) = illustratedPeople[index % illustratedPeople.length];
    return DecoratedBox(
      decoration: BoxDecoration(
        gradient: LinearGradient(begin: const Alignment(-0.5, -1), end: const Alignment(0.5, 1), colors: [Color(a), Color(b)]),
      ),
      child: Align(
        alignment: Alignment.bottomCenter,
        child: FractionallySizedBox(
          widthFactor: 0.93,
          child: AspectRatio(
            aspectRatio: 100 / 120,
            child: CustomPaint(painter: _PersonPainter(index % illustratedPeople.length)),
          ),
        ),
      ),
    );
  }
}

final _paths = <int, List<(Path, Paint)>>{};

class _PersonPainter extends CustomPainter {
  _PersonPainter(this.index);
  final int index;

  @override
  void paint(Canvas canvas, Size size) {
    final shapes = _paths.putIfAbsent(index, () {
      return [
        for (final (d, color, stroke) in illustratedPeople[index].$3)
          (
            parseSvgPath(d),
            Paint()
              ..color = Color(color)
              ..style = stroke == null ? PaintingStyle.fill : PaintingStyle.stroke
              ..strokeWidth = stroke ?? 0
              ..strokeCap = StrokeCap.round,
          ),
      ];
    });
    canvas.scale(size.width / 100);
    for (final (path, paint) in shapes) {
      canvas.drawPath(path, paint);
    }
  }

  @override
  bool shouldRepaint(_PersonPainter old) => old.index != index;
}
