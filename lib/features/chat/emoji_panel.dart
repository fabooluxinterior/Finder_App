/// A simple built-in emoji keyboard (no extra package). Taps insert at the cursor of the message box.
class EmojiPanel extends StatefulWidget {
  const EmojiPanel({super.key, required this.onPick, required this.onBackspace});
  final ValueChanged<String> onPick;
  final VoidCallback onBackspace;

  @override
  State<EmojiPanel> createState() => _EmojiPanelState();
}

class _EmojiPanelState extends State<EmojiPanel> {
  int _g = 0;

  @override
  Widget build(BuildContext context) {
    final c = context.fc;
    return Container(
      height: 270,
      decoration: BoxDecoration(
        color: c.surface,
        border: Border(top: BorderSide(color: c.hair)),
      ),
      child: Column(
        children: [
          SizedBox(
            height: 44,
            child: Row(
              children: [
                Expanded(
                  child: ListView(
                    scrollDirection: Axis.horizontal,
                    padding: const EdgeInsets.symmetric(horizontal: 8),
                    children: [
                      for (final (i, g) in _groups.indexed)
                        Semantics(
                          label: g.$2,
                          button: true,
                          child: InkWell(
                            borderRadius: BorderRadius.circular(12),
                            onTap: () => setState(() => _g = i),
                            child: Container(
                              width: 44,
                              alignment: Alignment.center,
                              decoration: BoxDecoration(
                                color: i == _g ? c.accent.withValues(alpha: 0.14) : null,
                                borderRadius: BorderRadius.circular(12),
                              ),
                              child: Text(g.$1, style: const TextStyle(fontSize: 22)),
                            ),
                          ),
                        ),
                    ],
                  ),
                ),
                IconButton(
                  onPressed: widget.onBackspace,
                  tooltip: 'Delete',
                  icon: Icon(Icons.backspace_outlined, color: c.ink2),
                ),
              ],
            ),
          ),
          Expanded(
            child: GridView.builder(
              padding: const EdgeInsets.fromLTRB(8, 0, 8, 8),
              gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(maxCrossAxisExtent: 46),
              itemCount: _groups[_g].$3.length,
              itemBuilder: (_, i) {
                final e = _groups[_g].$3[i];
                return InkWell(
                  borderRadius: BorderRadius.circular(10),
                  onTap: () => widget.onPick(e),
                  child: Center(child: Text(e, style: const TextStyle(fontSize: 26))),
                );
              },
            ),
          ),
        ],
      ),
    );
  }
}
