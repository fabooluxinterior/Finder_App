#!/usr/bin/env python3
"""Writes admin/lib/generated/migrations.g.dart from supabase/migrations.

The admin web app compares this list (what's in the repo) with the database's
schema_change_log (what's applied) to show pending migrations with their
description, tables and columns. CI fails if the file is out of date.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "admin" / "lib" / "generated" / "migrations.g.dart"


def header(text: str) -> dict:
    fields: dict[str, str] = {}
    key = None
    for line in text.splitlines()[:40]:
        m = re.match(r"^--\s*([a-z-]+)\s*:\s*(.*)$", line)
        if m:
            key = m.group(1)
            fields[key] = m.group(2).strip()
        elif key and re.match(r"^--\s{2,}\S", line):
            fields[key] += " " + line[2:].strip()
        else:
            key = None
    return fields


def first_comment(text: str) -> str:
    for line in text.splitlines()[:6]:
        t = line.lstrip("-= ").strip()
        if t:
            return t
    return ""


def main() -> None:
    items = []
    for f in sorted((ROOT / "supabase" / "migrations").glob("*.sql")):
        text = f.read_text()
        h = header(text)
        items.append({
            "id": f.stem,
            "description": h.get("description") or first_comment(text),
            "tables": h.get("tables", ""),
            "columns": h.get("columns-added", ""),
            "compat": h.get("backward-compat", ""),
            "recovery": h.get("recovery", ""),
            "userData": h.get("user-data", ""),
        })
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(
        "  RepoMigration(" + ", ".join(f"{k}: {json.dumps(v, ensure_ascii=False).replace('$', '\\$')}" for k, v in i.items()) + ")"
        for i in items)
    OUT.write_text(
        "// GENERATED by tool/gen_admin_manifest.py from supabase/migrations. Don't edit.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n"
        "import '../models.dart';\n\n"
        "const repoMigrations = <RepoMigration>[\n" + body + ",\n];\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(items)} migrations)")


if __name__ == "__main__":
    main()
